    fun loadEmojisFromFont(context: Context, fontFile: File): List<EmojiItem> {
        if (!fontFile.exists() || fontFile.length() == 0L) {
            return emptyList()
        }
        val typeface = try {
            android.graphics.Typeface.createFromFile(fontFile)
        } catch (e: Exception) {
            e.printStackTrace()
            return emptyList()
        }

        val paint = android.graphics.Paint().apply {
            this.typeface = typeface
            textSize = 32f
        }

        val allChars = mutableSetOf<String>()
        allChars.addAll(candidateEmojis)

        // Add standard emoji code point ranges
        for (codePoint in 0x1F000..0x1FAFF) {
            val s = String(Character.toChars(codePoint))
            allChars.add(s)
        }
        for (codePoint in 0x2600..0x27BF) {
            val s = String(Character.toChars(codePoint))
            allChars.add(s)
        }

        val supported = mutableListOf<EmojiItem>()
        for (emoji in allChars) {
            if (paint.hasGlyph(emoji)) {
                supported.add(
                    EmojiItem(
                        emoji = emoji,
                        name = "Emoji $emoji",
                        category = "TTF Font",
                        keywords = listOf("emoji", "ttf", emoji)
                    )
                )
            }
        }
        return supported.sortedBy { it.emoji }
    }
