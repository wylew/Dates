package com.wylew.dates.util

import android.content.Context
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.fonts.Font
import android.graphics.fonts.FontFamily
import android.os.Build
import com.wylew.dates.model.DateEvent
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import java.io.File

/** The emoji styles the picker offers; the order here is the picker's tab order */
enum class EmojiLibrary(val label: String) {
    SYSTEM("System"),
    SEGOE("Segoe UI"),
    FLUENT("Fluent 3D"),
    MONA("Mona Font"),
    OPENMOJI("OpenMoji")
}

/**
 * One pickable emoji from any library, in the shape events store it: [emoji] is the Unicode
 * character when known, [imageUri] the image path (or "font:mona") that renders it in this
 * library's style, null for plain system emoji. [tones] holds skin-tone variants' imageUris.
 * Emoji strings in [emoji] and [toneEmojis] may omit variation selector 16; compare with [sameEmoji].
 */
data class LibraryEmoji(
    val id: String,
    val name: String,
    val category: String,
    val keywords: List<String>,
    val emoji: String?,
    val imageUri: String?,
    val tones: List<String> = emptyList(),
    /** The exact emoji each of [tones] shows (base first), when known */
    val toneEmojis: List<String> = emptyList()
)

fun sameEmoji(a: String, b: String) = a.replace("\uFE0F", "") == b.replace("\uFE0F", "")

/** Category for library images with no Unicode emoji (OpenMoji extras); sorts last */
const val EXTRAS_CATEGORY = "Extras"

/**
 * Loads every library into [LibraryEmoji]s ordered and grouped by the Unicode emoji groups, using
 * the metadata generated by tools/build_emoji_metadata.py. Results are cached for the process.
 */
object EmojiLibraries {
    @Serializable
    private data class IndexEntry(val e: String, val n: String, val g: String, val k: List<String> = emptyList())

    @Serializable
    private data class PackEntry(
        val file: String,
        val name: String,
        val category: String,
        val keywords: List<String> = emptyList(),
        val emoji: String? = null,
        val tones: List<String> = emptyList()
    )

    private val json = Json { ignoreUnknownKeys = true }
    private val cache = mutableMapOf<EmojiLibrary, List<LibraryEmoji>>()
    private var indexCache: List<IndexEntry>? = null

    // Variation selector 16 is optional in emoji text; strip it so lookups match either form
    private fun normalize(emoji: String) = emoji.replace("️", "")

    private fun index(context: Context): List<IndexEntry> = indexCache ?: run {
        val entries = context.assets.open("emoji_index.json").bufferedReader().use {
            json.decodeFromString<List<IndexEntry>>(it.readText())
        }
        entries.also { indexCache = it }
    }

    private fun indexByEmoji(context: Context) = index(context).associateBy { normalize(it.e) }

    private fun withCurated(emoji: String?, keywords: List<String>): List<String> {
        val curated = emoji?.let { CuratedEmojiKeywords.byEmoji[it] ?: CuratedEmojiKeywords.byEmoji[normalize(it)] }
        return if (curated == null) keywords else (keywords + curated).distinct()
    }

    fun isAvailable(context: Context, library: EmojiLibrary): Boolean = when (library) {
        EmojiLibrary.SYSTEM -> true
        EmojiLibrary.FLUENT -> FluentEmojiManager.isPackDownloaded(context)
        EmojiLibrary.MONA -> MonaFontManager.isFontDownloaded(context)
        EmojiLibrary.OPENMOJI -> OpenMojiManager.isPackDownloaded(context)
        EmojiLibrary.SEGOE -> SegoeSvgManager.isPackDownloaded(context)
    }

    /** All emojis in [library], in Unicode order; empty if the library's assets are missing. Call off the main thread. */
    @Synchronized
    fun load(context: Context, library: EmojiLibrary): List<LibraryEmoji> = cache.getOrPut(library) {
        if (!isAvailable(context, library)) return emptyList()
        when (library) {
            EmojiLibrary.SYSTEM -> fromIndex(context, null) { Paint().hasGlyph(it) }
            EmojiLibrary.MONA -> loadMona(context)
            EmojiLibrary.FLUENT -> loadCodepointPack(
                context,
                FluentEmojiManager.assetFiles(context).map { it to "file:///android_asset/${FluentEmojiManager.ASSET_DIR}/$it" }
            )
            EmojiLibrary.SEGOE -> loadPack(context, "segoe_svgs") { "file:///android_asset/segoe_svgs/$it" }
            EmojiLibrary.OPENMOJI -> loadCodepointPack(
                context,
                OpenMojiManager.getDownloadedEmojis(context).map { File(it.filePath).name to it.filePath }
            )
        }
    }

    /**
     * [emoji] in [library]'s style, as the (emoji, imageUri) pair events store. Falls back to the
     * plain system emoji when the library doesn't have it.
     */
    fun resolve(context: Context, library: EmojiLibrary, emoji: String): Pair<String, String?> {
        val match = load(context, library).firstOrNull { it.emoji != null && normalize(it.emoji) == normalize(emoji) }
        return emoji to match?.imageUri
    }

    /**
     * The exact emoji an event shows: its stored character for system and font emoji, otherwise
     * looked up from its image (older events stored only the image). Null if it isn't a known emoji.
     */
    fun emojiOf(context: Context, event: DateEvent): String? {
        val uri = event.imageUri
        if (uri == null || uri == "font:mona") return event.emoji
        return emojiOfImage(context, uri) ?: event.emoji
    }

    /** The exact emoji a library image shows, or null if it isn't one of the libraries' images */
    private fun emojiOfImage(context: Context, uri: String): String? {
        for (library in EmojiLibrary.entries) {
            for (item in load(context, library)) {
                if (item.imageUri == uri) return item.emoji
                val toneIndex = item.tones.indexOf(uri)
                if (toneIndex >= 0) return item.toneEmojis.getOrNull(toneIndex)
            }
        }
        return null
    }

    // Pattern entries are image paths for image libraries, plain characters otherwise
    private fun isImagePattern(entry: String) = entry.startsWith("/") || entry.startsWith("file:") || entry.startsWith("asset:")

    /** A background-pattern entry in [library]'s style, or null if there's no exact match */
    private fun restylePatternEntry(context: Context, entry: String, library: EmojiLibrary): String? {
        val emoji = if (isImagePattern(entry)) emojiOfImage(context, entry) else entry
        val (matchEmoji, matchUri) = exactMatch(context, library, emoji ?: return null) ?: return null
        // Font emojis are stored as their character; the pattern draws them with the event's font
        return if (matchUri == null || matchUri == "font:mona") matchEmoji else matchUri
    }

    /**
     * [emoji] in [library]'s style as an (emoji, imageUri) pair, only if the library has that exact
     * emoji (skin tone included); null otherwise.
     */
    fun exactMatch(context: Context, library: EmojiLibrary, emoji: String): Pair<String, String?>? {
        // The system font draws any emoji it supports, including skin-tone sequences it doesn't list
        if (library == EmojiLibrary.SYSTEM) return if (Paint().hasGlyph(emoji)) emoji to null else null
        for (item in load(context, library)) {
            if (item.emoji != null && sameEmoji(item.emoji, emoji)) return emoji to item.imageUri
            val toneIndex = item.toneEmojis.indexOfFirst { sameEmoji(it, emoji) }
            if (toneIndex >= 0) return emoji to item.tones[toneIndex]
        }
        return null
    }

    /**
     * Events re-styled to [library]: the main emoji and each background-pattern emoji switch when
     * the library has an exact match, and stay as they are otherwise. Only events that would
     * actually change are returned.
     */
    fun restyle(context: Context, events: List<DateEvent>, library: EmojiLibrary): List<DateEvent> =
        events.mapNotNull { event ->
            val main = emojiOf(context, event)?.let { exactMatch(context, library, it) }
            val pattern = event.patternEmojis.map { restylePatternEntry(context, it, library) ?: it }
            val restyled = event.copy(
                emoji = main?.first ?: event.emoji,
                imageUri = if (main != null) main.second else event.imageUri,
                patternEmojis = pattern
            )
            val mainUnchanged = restyled.imageUri == event.imageUri &&
                (restyled.emoji == event.emoji || (restyled.emoji != null && event.emoji != null && sameEmoji(restyled.emoji, event.emoji)))
            if (mainUnchanged && pattern == event.patternEmojis) null else restyled
        }

    private fun fromIndex(context: Context, imageUri: String?, hasGlyph: (String) -> Boolean) =
        index(context).filter { hasGlyph(it.e) }.map {
            LibraryEmoji(it.e, it.n, it.g, withCurated(it.e, it.k), it.e, imageUri)
        }

    private fun loadMona(context: Context): List<LibraryEmoji> {
        val file = MonaFontManager.getFontFile(context)
        // Without a fallback chain hasGlyph only reports glyphs Mona itself draws (API 29+)
        val typeface = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
            Typeface.CustomFallbackBuilder(FontFamily.Builder(Font.Builder(file).build()).build()).build()
        } else {
            Typeface.createFromFile(file)
        }
        val paint = Paint().apply { this.typeface = typeface }
        return fromIndex(context, "font:mona") { paint.hasGlyph(it) }
    }

    private fun loadPack(context: Context, folder: String, uriFor: (String) -> String): List<LibraryEmoji> {
        val entries = context.assets.open("$folder/metadata.json").bufferedReader().use {
            json.decodeFromString<List<PackEntry>>(it.readText())
        }
        return entries.map {
            LibraryEmoji(
                id = it.file,
                name = it.name,
                category = it.category,
                keywords = withCurated(it.emoji?.ifBlank { null }, it.keywords),
                emoji = it.emoji?.ifBlank { null },
                imageUri = uriFor(it.file),
                tones = it.tones.map(uriFor)
            )
        }
    }

    /**
     * Packs whose files are named by codepoint ("1f600.webp", "1F468-200D-1F469.png") are matched
     * to the Unicode index directly; skin-tone files become tones of their base emoji.
     */
    private fun loadCodepointPack(context: Context, files: List<Pair<String, String>>): List<LibraryEmoji> {
        val byEmoji = indexByEmoji(context)
        val order = index(context).withIndex().associate { normalize(it.value.e) to it.index }
        val skinTones = (0x1F3FB..0x1F3FF).map { String(Character.toChars(it)) }
        fun withoutTones(chars: String) = skinTones.fold(chars) { s, t -> s.replace(t, "") }

        // (fileName, imageUri) -> the emoji characters its name spells out
        val parsed = files.mapNotNull { (fileName, uri) ->
            runCatching {
                fileName.substringBeforeLast('.').split("-")
                    .joinToString("") { String(Character.toChars(it.toInt(16))) }
            }.getOrNull()?.let { normalize(it) to (fileName to uri) }
        }
        val (toned, base) = parsed.partition { (chars, _) -> skinTones.any { it in chars } }
        // base chars -> (uri, exact toned chars), in file order
        val tonesByBase = toned.groupBy({ withoutTones(it.first) }, { it.second.second to it.first })
            .mapValues { (_, variants) -> variants.sortedBy { it.first } }

        return base.map { (chars, file) ->
            val (fileName, uri) = file
            val entry = byEmoji[chars]
            val tones = tonesByBase[chars].orEmpty()
            LibraryEmoji(
                id = fileName,
                name = entry?.n ?: fileName.substringBeforeLast('.'),
                category = entry?.g ?: EXTRAS_CATEGORY,
                keywords = withCurated(entry?.e, entry?.k ?: emptyList()),
                emoji = entry?.e,
                imageUri = uri,
                tones = if (tones.isEmpty()) emptyList() else listOf(uri) + tones.map { it.first },
                toneEmojis = if (tones.isEmpty()) emptyList() else listOf(entry?.e ?: chars) + tones.map { it.second }
            ) to (order[chars] ?: Int.MAX_VALUE)
        }.sortedBy { it.second }.map { it.first }
    }
}
